// ---- Main ---------------------------------------------------------------

async function migrate() {
  for (const item of ingredients) {
    console.log(`\nProcessing: ${item.name}`);

    const image = await uploadImage(item.image);
    if (image) console.log(`  ✓ Image uploaded`);

    const doc = {
      _id: `ingredient-${item.slug}`, // fixed id => reruns overwrite, not duplicate
      _type: "ingredient",
      name: item.name,
      slug: { _type: "slug", current: item.slug },
      description: item.description,
      ...(image ? { image } : {}),
      introduction: textToBlocks(item.introduction),
      howItWorks: textToBlocks(item.howItWorks),
      benefits: listToBlocks(item.benefits),
      bestFor: listToBlocks(item.bestFor),
      howToUse: textToBlocks(item.howToUse),
      pairsWith: listToBlocks(item.pairsWith),
      avoidWith: listToBlocks(item.avoidWith),
      proTip: textToBlocks(item.proTip),
      faqs: item.faqs.map((f) => ({
        _type: "faq",
        _key: randKey(),
        question: f.question,
        answer: textToBlocks(f.answer),
      })),
    };

    await client.createOrReplace(doc);
    console.log(`  ✓ Created/updated in Sanity as _id: ${doc._id}`);
  }

  console.log("\nDone. Check Sanity Studio — all 4 ingredients should now appear.");
}

migrate().catch((err) => {
  console.error("\nMigration failed:", err.message);
  process.exit(1);
});