/**
 * One-time migration script: pushes Vitamin C, Niacinamide, Retinol, and
 * Hyaluronic Acid from app/data/ingredients.ts into Sanity as real
 * documents, matching the `ingredient` schema (Portable Text fields).
 *
 * SETUP
 * 1. In your glowskin project folder, install the Sanity client:
 *      npm install @sanity/client
 *
 * 2. Create a write-enabled API token:
 *      https://www.sanity.io/manage -> your project (3x2g2pvc) -> API -> Tokens
 *      -> Add API token -> Permissions: "Editor" (or "Write")
 *      Copy the token (you only see it once).
 *
 * 3. Set it as an environment variable before running (don't hardcode it,
 *    don't commit it):
 *
 *      PowerShell:   $env:SANITY_WRITE_TOKEN="your-token-here"
 *      Cmd:          set SANITY_WRITE_TOKEN=your-token-here
 *      Mac/Linux:    export SANITY_WRITE_TOKEN=your-token-here
 *
 * 4. Run this file from your project root (so the relative image paths
 *    below resolve correctly):
 *      node migrate-ingredients.js
 *
 * This script is idempotent — it uses a fixed _id per ingredient
 * (e.g. "ingredient-vitamin-c") and createOrReplace, so running it again
 * won't create duplicates; it'll just overwrite with the same data.
 */

const { createClient } = require("@sanity/client");
const fs = require("fs");
const path = require("path");

const client = createClient({
  projectId: "3x2g2pvc",
  dataset: "production",
  apiVersion: "2024-01-01",
  token: process.env.SANITY_WRITE_TOKEN,
  useCdn: false,
});

if (!process.env.SANITY_WRITE_TOKEN) {
  console.error(
    "Missing SANITY_WRITE_TOKEN environment variable. See the setup notes at the top of this file."
  );
  process.exit(1);
}

// ---- Portable Text helpers -------------------------------------------

function randKey() {
  return Math.random().toString(36).slice(2, 10);
}

// Converts a single plain-text string into one Portable Text paragraph block.
function textToBlocks(text) {
  if (!text) return [];
  return [
    {
      _type: "block",
      _key: randKey(),
      style: "normal",
      children: [{ _type: "span", _key: randKey(), text, marks: [] }],
      markDefs: [],
    },
  ];
}

// Converts a string array into a Portable Text bullet list (one block per item).
function listToBlocks(items) {
  if (!items || items.length === 0) return [];
  return items.map((item) => ({
    _type: "block",
    _key: randKey(),
    style: "normal",
    listItem: "bullet",
    level: 1,
    children: [{ _type: "span", _key: randKey(), text: item, marks: [] }],
    markDefs: [],
  }));
}

// ---- Image upload helper ----------------------------------------------

async function uploadImage(relativePath) {
  const absolutePath = path.join(process.cwd(), "public", relativePath.replace(/^\/?images/, "images"));
  if (!fs.existsSync(absolutePath)) {
    console.warn(`  ! Image not found at ${absolutePath} — skipping image for this document.`);
    return null;
  }
  const buffer = fs.readFileSync(absolutePath);
  const asset = await client.assets.upload("image", buffer, {
    filename: path.basename(absolutePath),
  });
  return {
    _type: "image",
    asset: { _type: "reference", _ref: asset._id },
  };
}

